#!/usr/bin/env python3
"""Measure delivered PCM assets; report RMS/peak levels and objective loop-boundary review flags."""
import argparse, json, math, pathlib, struct, wave
ROOT=pathlib.Path(__file__).resolve().parents[1]
def db(value): return round(20*math.log10(max(value,1/32768)),3)
def measure(path,loop):
    with wave.open(str(path)) as w:
        rate=w.getframerate(); count=w.getnframes(); samples=struct.unpack('<'+'h'*count,w.readframes(count))
    peak=max(abs(x) for x in samples)/32768
    rms=math.sqrt(sum(x*x for x in samples)/count)/32768
    result={'file':path.name,'peak_dbfs':db(peak),'rms_dbfs':db(rms),'seconds':round(count/rate,4),'loop':loop,'review_flags':[]}
    if loop:
        step=abs(samples[-1]-samples[0])/32768
        slope=abs((samples[1]-samples[0])-(samples[-1]-samples[-2]))/32768
        edges=list(samples[:1024])+list(samples[-1024:])
        derivatives=sorted(abs(edges[i]-edges[i-1])/32768 for i in range(1,len(edges)))
        typical=derivatives[int(len(derivatives)*.95)]
        window=int(.02*rate)
        head=math.sqrt(sum(x*x for x in samples[:window])/window)/32768
        tail=math.sqrt(sum(x*x for x in samples[-window:])/window)/32768
        result.update(seam_step_dbfs=db(step),seam_slope_delta_dbfs=db(slope),boundary_rms_delta_db=round(abs(db(head)-db(tail)),3))
        if step>10**(-60/20): result['review_flags'].append('boundary amplitude step > -60 dBFS')
        if slope>max(3*typical,.005): result['review_flags'].append('unusual boundary slope change')
        if abs(db(head)-db(tail))>6: result['review_flags'].append('head/tail energy differs > 6 dB')
    return result

def build(folder):
    manifest=json.loads((folder/'manifest.json').read_text()); banks={}
    for key,entries in manifest['families'].items():
        clips=[measure(folder/e['file'],e['loop']) for e in entries]
        banks[key]={'peak_dbfs_max':max(x['peak_dbfs'] for x in clips),'rms_dbfs_min':min(x['rms_dbfs'] for x in clips),'rms_dbfs_max':max(x['rms_dbfs'] for x in clips),'clips':clips}
    flags=[{'file':x['file'],'flags':x['review_flags']} for b in banks.values() for x in b['clips'] if x['review_flags']]
    return {'metric':'full-clip PCM peak/RMS dBFS, not LUFS or perceptual loudness','targets':manifest['normalization'],'bank_count':len(banks),'clip_count':sum(len(x['clips']) for x in banks.values()),'seam_review_flags':flags,'banks':banks}

def markdown(report):
    lines=['# Combat audio level report','','Generated by `python3 tools/report_combat_audio.py`. Measurements use actual delivered PCM, not manifest estimates. Full-clip RMS is not perceptual LUFS; spectral balance and audible seams still require listening.','','One-shots target **-22 dBFS RMS**; sustained loops target **-24 dBFS RMS**. Peak ceilings are 0.70 (-3.10 dBFS) and 0.42 (-7.54 dBFS), with offline crest compression when needed. Runtime spatial distance, settings, concurrent-voice gain and the CombatSFX limiter also affect the mix.','',f"{report['clip_count']} clips / {report['bank_count']} banks. Objective loop-boundary flags: **{len(report['seam_review_flags'])}**. A zero boundary step does not prove a loop is inaudible. Listen for clicks, a volume dip every two seconds, periodic thumps and spectral changes across the wrap.",'','| Bank | Peak max dBFS | RMS min–max dBFS (3 variants) |','|---|---:|---:|']
    for key,b in report['banks'].items(): lines.append(f"| {key} | {b['peak_dbfs_max']:.2f} | {b['rms_dbfs_min']:.2f} – {b['rms_dbfs_max']:.2f} |")
    if report['seam_review_flags']:
        lines+=['','## Loops needing review','']+[f"- `{x['file']}`: {', '.join(x['flags'])}." for x in report['seam_review_flags']]
    lines+=['','Per-clip durations, peak/RMS and loop-step/slope/energy diagnostics are in `combat-audio-levels.json`.','']
    return '\n'.join(lines)
if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--folder',type=pathlib.Path,default=ROOT/'godot/assets/audio/combat');p.add_argument('--out',type=pathlib.Path,default=ROOT/'docs');args=p.parse_args()
    report=build(args.folder);args.out.mkdir(parents=True,exist_ok=True)
    (args.out/'combat-audio-levels.json').write_text(json.dumps(report,indent=2)+'\n')
    (args.out/'combat-audio-levels.md').write_text(markdown(report))
    print(f"Measured {report['clip_count']} clips / {report['bank_count']} banks; {len(report['seam_review_flags'])} loop review flags; report in {args.out}")
